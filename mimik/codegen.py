# Words in a hostname label that carry no identity (api.example.com -> Example).
_GENERIC_LABEL_WORDS = {
    "api", "www", "app", "prod", "production", "mobile", "web", "gateway",
    "edge", "cdn", "static", "live", "v1", "v2", "v3", "internal", "public",
}

# The generated-client marker (item 29): the header line the
# deterministic generator writes into every client. The Clients tab
# smoke test only runs files carrying it without asking — a file
# without it is foreign until the user explicitly confirms it.
GENERATED_MARKER = "generated by MIMIK"


def is_generated_client(path):
    """True when a file carries the generated-client marker in its
    first 4 KiB. Unreadable, undecodable, or missing files read as
    False — foreign until proven otherwise."""
    try:
        with open(path, "r", encoding="utf-8", errors="strict") as fh:
            head = fh.read(4096)
    except (OSError, ValueError):
        return False
    return GENERATED_MARKER in head


def preview_client(path):
    """(v0.6 T12) The preview facts for a kept client file: host,
    method list, generated date — parsed with ast, never exec, never
    imported. Returns None when the file cannot be read or parsed;
    otherwise a dict with host (None when the file carries no HOST
    assignment), methods (def names, dunders excluded), and date
    (the file's own date, YYYY-MM-DD, None when it cannot be read).
    The generated client carries no date line, so the file's
    modification date is the honest generated date."""
    if str(path).endswith(".mjs"):
        return _preview_client_js(path)
    try:
        with open(path, "r", encoding="utf-8", errors="strict") as fh:
            source = fh.read()
    except (OSError, ValueError):
        return None
    try:
        tree = ast.parse(source)
    except SyntaxError:
        return None
    host = None
    methods = []
    for node in tree.body:
        if isinstance(node, ast.ClassDef):
            for stmt in node.body:
                if isinstance(stmt, ast.Assign) and host is None:
                    if any(isinstance(t, ast.Name) and t.id == "HOST"
                           for t in stmt.targets) \
                            and isinstance(stmt.value, ast.Constant) \
                            and isinstance(stmt.value.value, str):
                        host = stmt.value.value
                elif isinstance(stmt, ast.FunctionDef) \
                        and not stmt.name.startswith("_"):
                    methods.append(stmt.name)
        elif isinstance(node, ast.FunctionDef) \
                and not node.name.startswith("_"):
            methods.append(node.name)
    try:
        generated = date.fromtimestamp(os.path.getmtime(path)).isoformat()
    except OSError:
        generated = None
    return {"host": host, "methods": methods, "date": generated}

# POST to a bare verb endpoint keeps the verb: POST /like -> like().
_POST_VERBS = {
    "like", "unlike", "login", "logout", "log-in", "log-out", "signin",
    "signout", "signup", "register", "search", "send", "verify", "refresh",
    "reset", "subscribe", "unsubscribe", "follow", "unfollow", "block",
    "unblock", "report", "share", "upload", "download", "sync", "check",
    "confirm", "cancel", "accept", "decline", "approve", "reject", "join",
    "leave", "save", "publish", "unpublish", "archive", "restore", "pin",
    "unpin", "mute", "unmute", "flag", "vote", "rate", "comment", "react",
}

# Keys whose sample values must NEVER appear in generated code.
_SECRET_HINTS = ("token", "password", "secret", "apikey", "api_key", "auth",
                 "session", "cookie", "credential", "passwd", "private")


def _is_secret_key(key):
    k = key.lower()
    return any(h in k for h in _SECRET_HINTS)


def _snake(name):
    name = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name)
    name = re.sub(r"[^a-zA-Z0-9]+", "_", name).strip("_").lower()
    if name and name[0].isdigit():
        name = "n_" + name
    return name or "value"


def _camel(name):
    parts = [p for p in re.split(r"[^a-zA-Z0-9]+", name) if p]
    return "".join(p[:1].upper() + p[1:] for p in parts)


def _singular(word):
    if word.endswith("ies") and len(word) > 3:
        return word[:-3] + "y"
    if word.endswith("ses") and len(word) > 3:
        return word[:-2]
    if word.endswith("s") and not word.endswith("ss") and len(word) > 1:
        return word[:-1]
    return word


def _plural(word):
    if word.endswith(("s", "x", "z", "ch", "sh")):
        return word + "es"
    if word.endswith("y") and len(word) > 1 and word[-2] not in "aeiou":
        return word[:-1] + "ies"
    return word + "s"


def class_name_for_host(host):
    """ExampleClient for api.example.com; HingeawsClient for prod-api.hingeaws.net."""
    for label in host.split("."):
        words = [w for w in re.split(r"[^a-zA-Z0-9]+", label.lower()) if w]
        kept = [w for w in words if w not in _GENERIC_LABEL_WORDS]
        if kept:
            name = _camel("_".join(kept)) + "Client"
            # A class name can't start with a digit — an IP host like
            # 127.0.0.1 would give 127Client, a SyntaxError.
            if name[0].isdigit():
                name = "Host" + name
            return name
    return "ApiClient"


def _path_parts(path):
    """(name parts, path params) for a path, dropping versions and /api/.

    Id segments (numeric, UUID, long hex, prefixed ids) become by_<name>
    parts with a matching parameter.
    """
    parts, params = [], []
    prev_name = None
    for seg in [s for s in path.split("/") if s]:
        m = re.fullmatch(r"\{(\w+)\}", seg)
        if m:
            name = _snake(m.group(1))
            params.append(name)
            parts.append("by_" + name)
        elif _looks_like_id(seg):
            name = (_singular(prev_name) + "_id") if prev_name else "id"
            name = _snake(name)
            if name not in params:
                params.append(name)
            parts.append("by_" + name)
        elif re.fullmatch(r"v\d+", seg, re.I) or seg.lower() == "api":
            continue
        else:
            parts.append(_snake(seg))
            prev_name = _snake(seg)
    return parts or ["index"], params


def method_name_for(method, path):
    """Deterministic method name from method + path.

    GET /rec/v2 -> get_recs, POST /like -> like, GET /users/{id} -> get_users_by_id.
    """
    parts, _params = _path_parts(path)
    joined = "_".join(parts)
    method = method.upper()
    if method == "GET":
        if (len(parts) == 1 and not parts[0].startswith("by_")
                and not parts[0].endswith("s")):
            return "get_" + _plural(parts[0])
        return "get_" + joined
    if method == "POST":
        if len(parts) == 1:
            if parts[0] in _POST_VERBS:
                return parts[0]
            return "create_" + _singular(parts[0])
        return "post_" + joined
    if method in ("PUT", "PATCH"):
        parts = [p if p.startswith("by_") else _singular(p) for p in parts]
        return "update_" + "_".join(parts)
    if method == "DELETE":
        parts = [p if p.startswith("by_") else _singular(p) for p in parts]
        return "delete_" + "_".join(parts)
    return _snake(method.lower()) + "_" + joined


def _looks_variable(key, value):
    """True when a sample body value must NOT be baked in as a literal.

    Only known-safe constant shapes are baked into the generated client:
    None, booleans, small ints (|v| <= 1000), and the empty string. Every
    non-empty string is treated as variable — a short string like "Josh"
    or "Dover" looks like a constant but is personal data, and baking it
    would leak it into any shared client (review #12). Such values become
    optional parameters with default None, so the sample never appears
    in the generated code at all.
    """
    if isinstance(value, bool) or value is None:
        return False
    if isinstance(value, int):
        return abs(value) > 1000  # big ints are ids; small ones are constants
    if isinstance(value, str):
        return bool(value)  # any non-empty string could be personal data
    return True  # float, dict, list: parameter, default None


def _params_for_endpoint(ep):
    """(params, literals, query_params) for one endpoint.

    params: [(py_name, json_key, default_repr_or_None, required)] — values
    that vary per call become method parameters. literals: {json_key: value}
    constants baked into the body template — only known-safe shapes
    (None, bool, small int, empty string; see _looks_variable).
    Secret-keyed values NEVER appear as literals, and neither do
    non-empty strings.
    """
    params, literals = [], {}
    body = {}
    if ep.get("request_body"):
        try:
            parsed = json.loads(ep["request_body"])
            if isinstance(parsed, dict):
                body = parsed
        except ValueError:
            pass
    for key, value in body.items():
        py = _snake(key)
        if _is_secret_key(key):
            params.append((py, key, None, False))
        elif _looks_variable(key, value):
            if isinstance(value, (dict, list)):
                params.append((py, key, None, False))
            elif isinstance(value, (int, float)) and not isinstance(value, bool) \
                    and abs(value) <= 1000:
                params.append((py, key, repr(value), False))
            else:
                params.append((py, key, None, False))
        else:
            literals[key] = value
    query_params = []
    for key, _val in parse_qsl(ep.get("query") or ""):
        py = _snake(key)
        if py not in [p[0] for p in params]:
            query_params.append((py, key))
    return params, literals, query_params


def _render_method(ep, used_names):
    """Render one endpoint as a method source block. Returns (name, source)."""
    method, path = ep["method"].upper(), ep["path"]
    base = method_name_for(method, path)
    if ep.get("websocket") and not base.endswith("_ws"):
        base += "_ws"
    name = base
    n = 2
    while name in used_names:
        name = f"{base}_{n}"
        n += 1
    used_names.add(name)
    if ep.get("websocket"):
        return name, _render_ws_method(ep, name)

    _parts, path_params = _path_parts(path)
    params, literals, query_params = _params_for_endpoint(ep)

    sig_parts = list(path_params)
    for py, _key, default, _req in params:
        if py in sig_parts:
            continue
        # Body params are always optional: default None, or a literal default.
        sig_parts.append(f"{py}={default}" if default is not None
                         else f"{py}=None")
    for py, _key in query_params:
        if py not in [s.split("=")[0] for s in sig_parts]:
            sig_parts.append(f"{py}=None")
    sig = ", ".join(["self"] + sig_parts)

    lines = [f"    def {name}({sig}):"]
    # Path with {param} placeholders for f-string substitution.
    url = _url_with_params(path)
    lines.append(f'        """{method} {url} -> {ep.get("status")}."""')
    if ep.get("samples") == 1:
        # v0.4 item 11: one captured call built this method — say so.
        lines.append("        # Single sample: one captured call built "
                     "this method.")

    use_json = method in ("POST", "PUT", "PATCH")
    body_lines = []
    if literals or params:
        if use_json:
            body_lines.append(f"        body = {literals!r}")
            for py, key, _d, _r in params:
                body_lines.append(f"        if {py} is not None:")
                body_lines.append(f"            body[{key!r}] = {py}")
        else:
            body_lines.append(f"        params = {literals!r}")
            for py, key, _d, _r in params:
                body_lines.append(f"        if {py} is not None:")
                body_lines.append(f"            params[{key!r}] = {py}")
    if query_params:
        if not any(l.startswith("        params = ") for l in body_lines):
            body_lines.append("        params = {}")
        for py, key in query_params:
            body_lines.append(f"        if {py} is not None:")
            body_lines.append(f"            params[{key!r}] = {py}")

    call_kw = []
    if use_json and (literals or params):
        call_kw.append("json=body")
    if not use_json and (literals or params or query_params):
        call_kw.append("params=params")
    if use_json and query_params:
        call_kw.append("params=params")

    url_expr = f'"{url}"'
    if path_params:
        url_expr = f'f"{url}"'
    call = f"self.{method.lower()}({url_expr}"
    if call_kw:
        call += ", " + ", ".join(call_kw)
    call += ")"
    lines.extend(body_lines)
    lines.append(f"        return {call}")
    return name, "\n".join(lines)


def _render_ws_method(ep, name):
    """A WebSocket endpoint as a ws_replay method (v0.4 item 13).

    The captured client->server messages are embedded as the default
    session; pass messages=[...] to send something else. Text embeds
    as a string, binary as bytes.fromhex(...).
    """
    method, path = ep["method"].upper(), ep["path"]
    _parts, path_params = _path_parts(path)
    url = _url_with_params(path)
    sig = ", ".join(["self"] + path_params + ["messages=None"])
    url_expr = f'f"{url}"' if path_params else f'"{url}"'
    lines = [f"    def {name}({sig}):",
             f'        """{method} {url} -> {ep.get("status")} (WebSocket)."""']
    if ep.get("samples") == 1:
        lines.append("        # Single sample: one captured call built "
                     "this method.")
    literals = []
    for message in ep.get("ws_messages") or []:
        if not message.get("from_client"):
            continue
        if message.get("b64") is not None:
            try:
                raw = base64.b64decode(message["b64"])
            except (ValueError, TypeError):
                continue
            literals.append(f"bytes.fromhex({raw.hex()!r})")
        else:
            literals.append(repr(message.get("text", "")))
    lines.append("        if messages is None:")
    if literals:
        lines.append(f"            messages = [{', '.join(literals)}]")
    else:
        lines.append("            messages = []  # no client messages "
                     "captured")
    lines.append(f"        return self.ws_replay({url_expr}, messages)")
    return "\n".join(lines)


def _url_with_params(path):
    """Rewrite a captured path so ids become {param} slots.

    /users/{user_id} stays as-is (snake-cased); /users/123 becomes
    /users/{user_id}; plain paths are unchanged.
    """
    segs = [s for s in path.split("/") if s]
    out = []
    prev_name = None
    for seg in segs:
        m = re.fullmatch(r"\{(\w+)\}", seg)
        if m:
            out.append("{" + _snake(m.group(1)) + "}")
        elif _looks_like_id(seg):
            name = (_singular(prev_name) + "_id") if prev_name else "id"
            out.append("{" + _snake(name) + "}")
        else:
            out.append(seg)
            if not (re.fullmatch(r"v\d+", seg, re.I) or seg.lower() == "api"):
                prev_name = _snake(seg)
    return "/" + "/".join(out)


def _generalize_endpoints(endpoints):
    """Collapse endpoints by generalized shape — always, not preset-gated.

    /users/123 and /users/456 become one /users/{id} endpoint — the
    first sample's bodies win. Returns new dicts; the input is
    untouched. Without this, a first run (no preset learned yet)
    generates one method per concrete id. Sample counts (v0.4 item
    11) SUM across the merged endpoints — a generalized method built
    from two concrete endpoints is multi-sample by construction.
    """
    seen = {}
    out = []
    for ep in endpoints:
        key = (ep["method"].upper(), generalize_path(ep["path"]))
        if key in seen:
            merged = seen[key]
            merged["samples"] = (merged.get("samples", 1)
                                 + ep.get("samples", 1))
            continue
        merged = dict(ep)
        merged["path"] = key[1]
        seen[key] = merged
        out.append(merged)
    return out


def _preset_auth_block(host, preset, label=None):
    """The auth section for a generated client, or "" when the preset
    learned nothing about auth. Names only — never values.

    label names where the auth came from ("preset for <host>" by
    default, or "pattern <id>" when a pattern preset supplied it).
    """
    auth = (preset or {}).get("auth") or {}
    headers = auth.get("headers") or []
    schemes = auth.get("schemes") or []
    cookies = auth.get("cookies") or []
    token_eps = auth.get("token_endpoints") or []
    if not (headers or cookies or token_eps):
        return ""
    lines = ["    # Auth, learned from your captures "
             f"({label or f'preset for {host}'}):"]
    for h in headers:
        extra = ""
        if h.lower() == "authorization" and schemes:
            extra = f" ({', '.join(schemes)})"
        lines.append(f"    #   header: {h}{extra}")
    for c in cookies:
        lines.append(f"    #   cookie: {c}")
    for t in token_eps:
        lines.append(f"    #   sign-in: {t}")
    if headers:
        lines.append(f"    AUTH_HEADERS = {tuple(headers)!r}")
    if cookies:
        lines.append(f"    AUTH_COOKIES = {tuple(cookies)!r}")
    return "\n" + "\n".join(lines)


def generate_deterministic(host, endpoints, preset=None, preset_label=None,
                           applied=None):
    """The $0 generator: pure rules, no LLM, no network. Returns source.

    Endpoints always collapse by their generalized shape (/users/123
    and /users/456 become one /users/{id} method), preset or not — the
    preset's job is auth, scale, and asset-mapping, not basic path
    collapsing. With a preset (a dict from mimik.presets) the class
    also carries the learned auth section.
    preset_label names where the auth came from (default: the app
    preset); applied lists the presets that were used, and is
    printed as a comment naming them (app vs pattern).
    """
    cls = class_name_for_host(host)
    used = set()
    blocks = []
    eps = _generalize_endpoints(endpoints)
    for ep in eps:
        _name, src = _render_method(ep, used)
        blocks.append(src)
    methods = "\n\n".join(blocks) if blocks else "    pass"
    auth_block = (_preset_auth_block(host, preset, label=preset_label)
                  if preset is not None else "")
    applied_note = ""
    if applied:
        applied_note = "\n# Presets applied: " + "; ".join(applied)
    # v0.4 item 11: the docstring counts the single-sample methods.
    single = sum(1 for ep in eps if ep.get("samples") == 1)
    sample_note = ""
    if single:
        sample_note = (
            f"\n{single} of {len(eps)} "
            f"endpoint{'s' if len(eps) != 1 else ''} "
            f"come{'s' if single == 1 else ''} from a single captured "
            "sample, those methods are marked below. Re-record with "
            "more traffic to firm them up.\n")
    return f'''"""{cls}, {GENERATED_MARKER} from your own captured traffic.

Own accounts only: this client replays YOUR session for YOUR apps.
Auth is pulled from your live mitmweb or your saved capture, no tokens
are stored in this file. Requests time out after 30 s by default, pass timeout=... to the constructor or any call to change it.
Personal values from your captures (names, cities, and the like) are
method parameters, never baked-in literals.{sample_note}
Edit freely.
"""{applied_note}

from mimik import App


class {cls}(App):
    """Client for {host}."""

    HOST = "{host}"{auth_block}

{methods}


if __name__ == "__main__":
    print("methods:", ", ".join(
        m for m in dir({cls}) if not m.startswith("_")))
'''


def _preview_client_js(path):
    """The preview_client facts for a generated JavaScript client:
    host from its static HOST line, method names from its async
    methods (private helpers excluded), date from the file's
    modification time. Regex only: the file is never run or
    imported. Returns None when the file cannot be read."""
    try:
        with open(path, "r", encoding="utf-8", errors="strict") as fh:
            source = fh.read()
    except (OSError, ValueError):
        return None
    m = re.search(r'static\s+HOST\s*=\s*"([^"]+)"', source)
    host = m.group(1) if m else None
    methods = [name for name in
               re.findall(r"^\s+async\s+(\w+)\s*\(", source, re.M)
               if not name.startswith("_")]
    try:
        generated = date.fromtimestamp(os.path.getmtime(path)).isoformat()
    except OSError:
        generated = None
    return {"host": host, "methods": methods, "date": generated}


# ---- JavaScript client (v0.9, item 33: second language) --------------------
# A standalone Node ESM module (.mjs): zero dependencies, built-in
# fetch (Node 18+). It cannot subclass mimik.App (that is Python),
# so it carries its own small _request runtime in the same file.
# All the analysis is shared with the Python generator (method
# names, parameters, the secret and literal rules); only the
# rendering is new, so the two clients agree method for method.

def _js_literal(value):
    """A Python sample value as a JavaScript literal."""
    if value is None:
        return "null"
    if value is True:
        return "true"
    if value is False:
        return "false"
    if isinstance(value, (int, float)):
        return repr(value)
    return json.dumps(str(value))


