"""v0.9 (item 33): the JavaScript client generator.

The JS client is additive: the Python generator's output must be
untouched, and the JS module must carry the same method names,
the same secret rules, and the same preset auth names. Node
checks (parse + run) skip when node is not on the machine.
"""
import argparse
import io
import json
import os
import shutil
import subprocess
import sys
import tempfile
import unittest
from unittest import mock

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

from mimik import cli, codegen, store  # noqa: E402

NODE = shutil.which("node")

EPS = [
    {"method": "GET", "path": "/users/123", "query": "limit=5",
     "request_body": None, "response_body": "{}", "status": 200,
     "samples": 2},
    {"method": "GET", "path": "/users/456", "query": "",
     "request_body": None, "response_body": "{}", "status": 200,
     "samples": 1},
    {"method": "POST", "path": "/like", "query": "",
     "request_body": '{"post_id": 987654, "token": "sekrit123", '
                     '"note": "hello", "count": 3, "kind": "tap", '
                     '"flag": true, "misc": null}',
     "response_body": "{}", "status": 200, "samples": 1},
    {"method": "GET", "path": "/feed", "query": "",
     "request_body": None, "response_body": "{}", "status": 200,
     "samples": 1, "websocket": True,
     "ws_messages": [{"from_client": True, "text": "ping"},
                     {"from_client": False, "text": "pong"},
                     {"from_client": True, "b64": "AAE="}]},
]

PRESET = {"auth": {"headers": ["Authorization", "X-Api-Key"],
                   "schemes": ["Bearer"], "cookies": ["session_id"],
                   "token_endpoints": ["POST /login"]}}


def gen_js(**kw):
    kw.setdefault("preset", PRESET)
    kw.setdefault("preset_label", "preset for api.example.com")
    return codegen.generate_js("api.example.com", EPS, **kw)


class JsShapeTests(unittest.TestCase):
    def test_module_shape(self):
        src = gen_js()
        self.assertIn("generated by MIMIK", src)
        self.assertIn("export class ExampleClient", src)
        self.assertIn('static HOST = "api.example.com"', src)
        self.assertIn('from "node:url"', src)
        # Zero dependencies: the node:url import is the only one.
        self.assertEqual(src.count("import "), 1)
        self.assertIn("fetch(", src)

    def test_method_names_match_python(self):
        with tempfile.TemporaryDirectory() as td:
            py_path = os.path.join(td, "x_client.py")
            js_path = os.path.join(td, "x_client.mjs")
            with open(py_path, "w") as f:
                f.write(codegen.generate_deterministic(
                    "api.example.com", EPS, preset=PRESET))
            with open(js_path, "w") as f:
                f.write(gen_js())
            py_info = codegen.preview_client(py_path)
            js_info = codegen.preview_client(js_path)
        self.assertEqual(js_info["host"], "api.example.com")
        self.assertEqual(sorted(js_info["methods"]),
                         sorted(py_info["methods"]))
        self.assertIn("get_users_by_id", js_info["methods"])
        self.assertIn("like", js_info["methods"])
        self.assertIn("get_feeds_ws", js_info["methods"])
        self.assertIsNotNone(js_info["date"])

    def test_secrets_and_personal_values_never_appear(self):
        src = gen_js()
        self.assertNotIn("sekrit123", src)   # secret value
        self.assertNotIn("hello", src)       # non-empty string value
        self.assertNotIn("tap", src)         # non-empty string value
        self.assertNotIn("987654", src)      # big int id
        # ...while the parameter names do appear.
        self.assertIn("token", src)
        self.assertIn("post_id", src)

    def test_safe_literals_are_baked(self):
        src = gen_js()
        self.assertIn('"count": 3', src)
        self.assertIn('"flag": true', src)
        self.assertIn('"misc": null', src)

    def test_generalized_path_and_query(self):
        src = gen_js()
        self.assertIn("`/users/${id}`", src)
        self.assertIn('query["limit"] = limit', src)

    def test_auth_block_names_only(self):
        src = gen_js()
        self.assertIn("header: Authorization (Bearer)", src)
        self.assertIn("header: X-Api-Key", src)
        self.assertIn("cookie: session_id", src)
        self.assertIn("sign-in: POST /login", src)
        self.assertIn('static AUTH_HEADERS = '
                      '["Authorization", "X-Api-Key"]', src)
        self.assertIn("process.env", src)
        self.assertIn("MIMIK_COOKIE", src)

    def test_no_preset_no_auth_block(self):
        src = codegen.generate_js("api.example.com", EPS)
        self.assertNotIn("Auth, learned", src)
        self.assertIn("static AUTH_HEADERS = []", src)

    def test_single_sample_note(self):
        src = gen_js()
        self.assertIn("2 of 3 endpoints come from a single "
                      "captured sample", src)
        self.assertIn("// Single sample: one captured call built "
                      "this method.", src)

    def test_ws_method_defaults(self):
        src = gen_js()
        self.assertIn('messages = ["ping", Buffer.from("0001", '
                      '"hex")]', src)
        self.assertIn('return this._wsReplay("/feed", messages);',
                      src)

    def test_generate_lang_js_routes(self):
        src = codegen.generate("api.example.com", EPS, lang="js")
        self.assertIn("export class ExampleClient", src)
        py = codegen.generate("api.example.com", EPS)
        self.assertIn("from mimik import App", py)
        self.assertTrue(codegen._compiles(py))


@unittest.skipUnless(NODE, "node is not installed")
class JsNodeTests(unittest.TestCase):
    def _write(self, td):
        path = os.path.join(td, "api_example_com_client.mjs")
        with open(path, "w") as f:
            f.write(gen_js())
        return path

    def test_node_parses_the_client(self):
        with tempfile.TemporaryDirectory() as td:
            path = self._write(td)
            proc = subprocess.run([NODE, "--check", path],
                                  capture_output=True, text=True)
        self.assertEqual(proc.returncode, 0, proc.stderr)

    def test_node_main_guard_lists_methods(self):
        with tempfile.TemporaryDirectory() as td:
            path = self._write(td)
            proc = subprocess.run([NODE, path],
                                  capture_output=True, text=True)
        self.assertEqual(proc.returncode, 0, proc.stderr)
        self.assertIn("class: ExampleClient | HOST: "
                      "api.example.com", proc.stdout)
        self.assertIn("get_users_by_id", proc.stdout)
        self.assertIn("like", proc.stdout)


class JsCliTests(unittest.TestCase):
    def setUp(self):
        self._td = tempfile.TemporaryDirectory()
        self.addCleanup(self._td.cleanup)
        self._cwd = os.getcwd()
        os.chdir(self._td.name)
        self.addCleanup(os.chdir, self._cwd)
        patcher = mock.patch.dict(
            os.environ, {"MIMIK_DATA_DIR": os.path.join(
                self._td.name, "data")})
        patcher.start()
        self.addCleanup(patcher.stop)

    def _save_flows(self):
        def flow(fid, method, path, body=None):
            return {"id": fid, "request": {
                "host": "api.example.com", "method": method,
                "path": path, "scheme": "https", "port": 443,
                "headers": [], "body": body},
                "response": {"status_code": 200, "headers": []}}
        store.save_flows([flow("j1", "GET", "/users/123"),
                          flow("j2", "POST", "/like",
                               '{"count": 3}')])

    def test_gen_lang_js_writes_mjs_and_store_copy(self):
        self._save_flows()
        args = argparse.Namespace(
            host="api.example.com", har=None, curl=None, out=None,
            model=None, polish="none", prompt_only=False, lang="js")
        out = io.StringIO()
        with mock.patch("sys.stdout", out):
            cli.cmd_gen(args)
        path = os.path.join(self._td.name,
                            "api_example_com_client.mjs")
        self.assertTrue(os.path.isfile(path))
        with open(path) as f:
            src = f.read()
        self.assertIn("export class ExampleClient", src)
        self.assertIn('import { ExampleClient } from '
                      '"./api_example_com_client.mjs";',
                      out.getvalue())
        names = [n for n, _p, _s in store.list_clients()]
        self.assertEqual(names, ["api_example_com_client.mjs"])

    def test_gen_js_with_polish_notes_and_still_writes(self):
        self._save_flows()
        args = argparse.Namespace(
            host="api.example.com", har=None, curl=None, out=None,
            model=None, polish="ollama", prompt_only=False,
            lang="js")
        err = io.StringIO()
        with mock.patch("sys.stderr", err):
            cli.cmd_gen(args)
        self.assertIn("polish applies to Python clients",
                      err.getvalue())
        self.assertTrue(os.path.isfile(os.path.join(
            self._td.name, "api_example_com_client.mjs")))

    def test_unique_out_js_numbering(self):
        with open(os.path.join(self._td.name,
                               "api_example_com_client.mjs"),
                  "w") as f:
            f.write("x")
        self.assertEqual(
            cli._unique_out("api.example.com", self._td.name, "js"),
            "api_example_com_2_client.mjs")
        self.assertEqual(cli._default_out("api.example.com", "js"),
                         "api_example_com_client.mjs")


class JsStoreTests(unittest.TestCase):
    def setUp(self):
        self._td = tempfile.TemporaryDirectory()
        self.addCleanup(self._td.cleanup)
        self.base = os.path.join(self._td.name, "data")

    def test_mjs_copy_normalizes_and_lists(self):
        src = 'export class A {\n  static HOST = "a.com";\n}\n'
        path = store.save_client_copy("custom.mjs", src,
                                      base=self.base)
        self.assertTrue(path.endswith("custom_client.mjs"))
        names = [n for n, _p, _s in store.list_clients(self.base)]
        self.assertEqual(names, ["custom_client.mjs"])

    def test_mjs_other_host_gets_sibling(self):
        a = 'export class A {\n  static HOST = "a.com";\n}\n'
        b = 'export class B {\n  static HOST = "b.com";\n}\n'
        store.save_client_copy("same_client.mjs", a, base=self.base)
        path = store.save_client_copy("same_client.mjs", b,
                                      base=self.base)
        self.assertTrue(path.endswith("same_2_client.mjs"))
        names = [n for n, _p, _s in store.list_clients(self.base)]
        self.assertEqual(names, ["same_2_client.mjs",
                                 "same_client.mjs"])

    def test_mjs_delete_roundtrip_and_refusals(self):
        src = 'export class A {\n  static HOST = "a.com";\n}\n'
        store.save_client_copy("gone_client.mjs", src,
                               base=self.base)
        self.assertEqual(
            store.delete_client("gone_client.mjs",
                                base=self.base)["deleted"] is not None,
            True)
        self.assertEqual(store.list_clients(self.base), [])
        # A name without the generated suffix is refused.
        self.assertIsNone(store.delete_client(
            "plain.mjs", base=self.base)["deleted"])

    def test_python_and_js_clients_coexist(self):
        store.save_client_copy(
            "py_client.py", 'HOST = "a.com"\n', base=self.base)
        store.save_client_copy(
            "js_client.mjs",
            'export class A {\n  static HOST = "a.com";\n}\n',
            base=self.base)
        names = [n for n, _p, _s in store.list_clients(self.base)]
        self.assertEqual(names, ["js_client.mjs", "py_client.py"])

    def test_client_host_of_matches_static_host(self):
        src = 'export class A {\n  static HOST = "a.com";\n}\n'
        self.assertEqual(store._client_host_of(src), "a.com")
        self.assertEqual(store._client_host_of('HOST = "b.com"\n'),
                         "b.com")


if __name__ == "__main__":
    unittest.main()
